//! `pdks init` — write a commented starter config and the telemetry ignore line, leaving
//! anything already present alone.

use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::Path;

use crate::load_config::{CONFIG_FILENAMES, present_config_names};

const GITIGNORE: &str = ".gitignore";
const TELEMETRY_IGNORE_LINE: &str = ".polydeukes/";
const GITIGNORE_ENTRY: &str =
    "# Polydeukes telemetry — local observation data, never committed.\n.polydeukes/\n";

const GENERATED_CONFIG: &str = r"# Polydeukes protection policy — generated by `pdks init`.
#
# This file is data, never code. The judges read it, every verdict traces back to an entry
# below, and editing it is how you change what is judged.

# The protection list. A tool call whose proven target is one of these paths is blocked, and
# so is a shell command that mentions one. A path names the same file in this project and
# under the home directory.
#
# The list starts empty apart from the config file itself, which is always on it. Add the
# files that register your agent's hooks: editing them does not evade a judgment, it removes
# the judgment, and the session surface is the only layer that can watch it happen. An
# adapter's init adds the files it registers.
#
# This list is what blocks. Every `disciplines:` entry below lands at advise — a break is
# recorded and the call goes on — unless the entry itself says `enforce: block`.
protectedPaths: []

# The time-boxed witness — the human valve on a blocked verdict. A human types this token so
# it stands alone on a message's FIRST line, the window holds for ttlMinutes, then blocking
# resumes on its own. The valve is consulted only AFTER a verdict blocked, so an opened
# window is always recorded as `witnessed` and never silent, and no agent can open one for
# itself. The token is not a secret: the defence is provenance, not confidentiality.
#
# Keep this block. Without it no block can be opened by anyone, and once your agent's hook
# files are on the list above, the first block would freeze the project until a human edits
# these files from their own terminal.
witness:
  token: 'pdks witness'
  ttlMinutes: 10

# The disciplines you judge by, and the two rungs one climbs — shown as two entries so each
# rung is a line you can copy. Uncomment to start; ids must stay distinct.
#
# Three lists, chosen by what a declaration reads. `disciplines:` is judged on both
# surfaces (the changed file's own pre/post and file sources). `sessionDisciplines:` is
# judged only where a live call is observed before it runs (command line, transcript,
# actor). `changeSetDisciplines:` is judged only over a finished change set
# (`--diff`). The loader refuses an entry written in a list its channels do not fit.
#
# disciplines:
#   # A draft: prose only, no predicate. Registered and read, never judged.
#   - id: 'no-todo-in-shipped-code-draft'
#     why: 'a TODO nobody owns is a decision deferred out of sight'
#     draft: true
#
#   # Promoted to a judgment. Advise is the default — recorded as `advised`, never stops
#   # the call — so this line is optional; it is written here to show the rung.
#   #
#   # The declaration keys each side's matched lines by the matched text and breaks on what
#   # the edit ADDED, so occurrences already in the tree are forgiven.
#   - id: 'no-todo-in-shipped-code'
#     why: 'a TODO nobody owns is a decision deferred out of sight'
#     declare:
#       mechanism: 'added-only'
#       scope: { source: 'target.path', include: ['^src/'] }
#       supply: { pre: 'empty', post: 'empty' }
#       extract:
#         before:
#           - { op: 'source', of: 'pre' }
#           - { op: 'lines' }
#           - { op: 'keyByPattern', re: '(TODO)' }
#         after:
#           - { op: 'source', of: 'post' }
#           - { op: 'lines' }
#           - { op: 'keyByPattern', re: '(TODO)' }
#         added:
#           - { op: 'onlyIn', of: 'after', notIn: 'before', count: true }
#       relate:
#         - id: 'nothing-added'
#           relation: { op: 'empty', of: 'added' }
#           message: 'adds {key}: {value}'
#     enforce: advise
#   # The promotion — change `enforce: advise` to `enforce: block`. Block is your choice,
#   # never the default.
";

pub fn init(root: &Path) -> Result<String, String> {
    let found = present_config_names(root);
    if found.len() > 1 {
        return Err(format!(
            "ambiguous Polydeukes config in {} — found {}; keep exactly one and re-run",
            root.display(),
            found.join(" and ")
        ));
    }
    let mut report = Vec::new();
    if let [existing] = found.as_slice() {
        report.push(format!("skipped {existing} (already present)\n"));
    } else {
        let name = CONFIG_FILENAMES[0];
        OpenOptions::new()
            .write(true)
            .create_new(true)
            .open(root.join(name))
            .and_then(|mut file| file.write_all(GENERATED_CONFIG.as_bytes()))
            .map_err(|error| error.to_string())?;
        report.push(format!("created {name}\n"));
    }

    let path = root.join(GITIGNORE);
    let existing = if path.exists() {
        String::from_utf8_lossy(&fs::read(&path).map_err(|error| error.to_string())?).into_owned()
    } else {
        String::new()
    };
    if existing
        .split('\n')
        .any(|line| line.trim() == TELEMETRY_IGNORE_LINE)
    {
        report.push(format!("skipped {GITIGNORE} (already present)\n"));
    } else {
        let separator = if existing.is_empty() || existing.ends_with('\n') {
            ""
        } else {
            "\n"
        };
        OpenOptions::new()
            .create(true)
            .append(true)
            .open(&path)
            .and_then(|mut file| file.write_all(format!("{separator}{GITIGNORE_ENTRY}").as_bytes()))
            .map_err(|error| error.to_string())?;
        report.push(format!("created {GITIGNORE}\n"));
    }
    Ok(report.concat())
}
